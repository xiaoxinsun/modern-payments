\getenv temporal_password TEMPORAL_DB_PASSWORD
\getenv oidc_password OIDC_DB_PASSWORD
CREATE ROLE temporal LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD :'temporal_password';
CREATE ROLE oidc LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD :'oidc_password';
CREATE DATABASE temporal OWNER temporal;
CREATE DATABASE temporal_visibility OWNER temporal;
CREATE DATABASE oidc OWNER oidc;
REVOKE ALL ON DATABASE temporal FROM PUBLIC;
REVOKE ALL ON DATABASE temporal_visibility FROM PUBLIC;
REVOKE ALL ON DATABASE oidc FROM PUBLIC;
REVOKE ALL ON DATABASE postgres FROM PUBLIC;
\connect temporal
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
